// 키워드 FAQ(lib/faq.ts)에 매칭이 안 됐을 때, 예전에는 무조건 Gemini에게 넘겨서
// "어떻게든" 답을 하게 했습니다(날씨 질문은 외부 사이트로 안내하기도 했습니다).
// 팀 논의 결과 이제는 학사 관련 여부만 따집니다: 입력 문장에 아래
// IN_SCOPE_KEYWORDS 중 하나도 없으면(날씨, 스포츠, 잡담 등 전부 포함) Gemini를
// 아예 호출하지 않고 곧바로 BLOCKED_MESSAGE만 보여줍니다.
// (LLM 호출이 전혀 없어서 속도/비용/오작동 리스크가 없는 가장 안전한 방식)
//
// ★ 팀 회의 때 다루기로 한 주제(장학/등록/수강신청/성적/연락처)가 바뀌거나
//   늘어나면 아래 두 가지만 고치면 됩니다. 코드를 더 건드릴 필요 없어요.
//   1) BLOCKED_MESSAGE — 화면에 보여줄 고정 안내 문구
//   2) IN_SCOPE_KEYWORDS — 그 주제와 관련 있다고 인정할 키워드 목록
// =========================================================================

// 화이트리스트에 하나도 안 걸렸을 때 그대로 보여줄 고정 문구.
// 다루는 주제가 바뀌면 이 문장만 고치면 됩니다.
export const BLOCKED_MESSAGE =
  "저는 대림대학교 학사 안내만 도와드려요. 장학 · 등록 · 수강신청 · 성적 · 휴학 · 복학 · 전과 · 군 학점인정 · 통학버스 · 교내 연락처 중에서 질문해주세요.";

// 이 중 하나라도 입력 문장에 포함되면 "학사 관련 질문"으로 인정하고
// Gemini 자유 답변까지 넘어갈 수 있습니다. 하나도 없으면 그 자리에서 차단됩니다.
// 다루는 주제를 추가/삭제할 때는 이 배열만 수정하세요.
export const IN_SCOPE_KEYWORDS = [
  // 공통/학교 전반
  "대림", "학교", "학사", "학생", "캠퍼스", "대학교", "학번", "학과", "전공",
  "입학", "졸업", "휴학", "복학", "전과", "재학", "시간표", "학사일정",

  // 통학버스
  "통학버스", "셔틀버스", "셔틀", "안양역", "범계역",

  // 장학
  "장학",

  // 등록
  "등록",

  // 수강신청
  "수강", "강의", "과목", "학점", "교양", "재수강",

  // 성적
  "성적",

  // 교내 연락처
  "연락처", "전화", "문의", "부서", "행정실", "교직원",
];

export function isInScope(rawQuery: string): boolean {
  const query = rawQuery.trim();
  if (!query) return false;
  return IN_SCOPE_KEYWORDS.some((keyword) => query.includes(keyword));
}