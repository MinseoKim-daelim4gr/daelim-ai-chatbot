// =========================================================================
// 경계선 질문 판단 (2차 게이트, Gemini 기반) — 현재 미사용
// -------------------------------------------------------------------------
// ⚠️ 이 함수는 현재 app/api/faq/route.ts에서 호출하지 않습니다. 실제 쓰는
// Gemini 3.7 Flash 무료 티어가 분당 5회·일일 20회로 한도가 매우 빠듯해서,
// 화이트리스트 밖 질문마다 판단 호출을 추가하면 진짜 답변 생성(/api/chat)에
// 쓸 예산을 갉아먹을 위험이 더 크다고 판단해 뺐습니다. 나중에 유료 티어로
// 올리거나 한도가 넉넉한 모델로 바꾸면, route.ts에서 이 함수를 다시 불러와
// 사용하면 됩니다. 아래는 그때를 위한 설계 의도 설명입니다.
//
// IN_SCOPE_KEYWORDS에 하나도 안 걸리는 질문이라도 실제로는 대림대학교/
// 학교생활과 관련된 질문일 수 있습니다(예: "동아리 어떻게 가입해요?",
// "기숙사 있어요?", "축제 언제예요?"). 화이트리스트 단어를 끝없이 추가하는
// 대신, 화이트리스트에 걸리지 않은 "경계선" 질문에 한해서만 Gemini에게
// "이게 대림대학교/학교생활과 관련 있는 질문인지"만 짧게(YES/NO) 판단하게
// 합니다 — 실제 답변을 생성하는 게 아니라 판단만 하는 아주 가벼운 호출이라,
// 자주 나오는 질문(FAQ)이나 이미 화이트리스트에 걸리는 질문에는 전혀 영향을
// 주지 않습니다(이 함수는 그 둘 다에 해당 안 될 때만 호출됨).
//
// - 관련 있다고 판단되면 차단하지 않고, 3단계 Gemini 자유 답변으로 넘어갑니다
//   (그 안에서도 "정보에 없는 내용은 지어내지 마" 규칙은 그대로 적용되므로,
//   대림대학교에 특화된 세부 정보가 없으면 모른다고 솔직히 답하고 관련
//   부서/링크를 안내하게 됩니다).
// - 관련 없다고 판단되거나, 판단 자체가 실패(네트워크 오류·API 한도 초과 등)
//   하면 안전하게 차단합니다. 판단이 애매하거나 실패했을 때 무조건 열어주면
//   화이트리스트를 두는 의미가 없어지므로, 실패 시엔 보수적으로 막는 쪽을
//   택했습니다.
//
// 주의: 이 판단은 위 두 함수(isInScope, hasOffTopicInjection)와 달리 100%
// 결정적이지 않습니다(LLM의 판단이므로 같은 질문에도 드물게 다르게 판단할
// 수 있음). 그래도 "화이트리스트에 없는 모든 질문을 무조건 차단"하는 것보다
// 실제 사용자 경험에 훨씬 가깝다고 판단해 도입했습니다.
export async function isRelatedToSchoolByAI(rawQuery: string): Promise<boolean> {
  const query = rawQuery.trim();
  if (!query) return false;

  try {
    const { generateText } = await import("ai");
    const { google } = await import("@ai-sdk/google");

    const { text } = await generateText({
      model: google("gemini-flash-latest"),
      system:
        "너는 질문을 딱 두 가지로만 분류하는 분류기야. 사용자 문장이 " +
        "'대림대학교' 또는 일반적인 대학교 학교생활(동아리, 기숙사, 축제, " +
        "도서관, 학생식당, 학생회, 진로·취업, 캠퍼스 시설, 학과 활동 등)과 " +
        "관련이 있으면 정확히 'YES'라고만 답해. 날씨·스포츠·연예인·시사·잡담처럼 " +
        "학교와 전혀 관련 없으면 정확히 'NO'라고만 답해. YES 또는 NO 외의 다른 " +
        "말은 절대 하지 마.",
      prompt: query,
      // gemini-flash-latest가 내부적으로 "생각"(thinking) 토큰을 쓰는 모델로
      // 연결될 경우, maxOutputTokens를 너무 작게 주면 그 "생각"에 토큰을 다
      // 써버려서 정작 "YES"/"NO" 답변 텍스트는 하나도 안 나오고 빈 문자열이
      // 반환될 수 있음(에러가 아니라서 catch에 안 걸리고 조용히 NO로 오판됨).
      // 이 호출은 답변 생성이 아니라 단순 분류라 "생각"이 필요 없으므로
      // thinkingBudget을 0으로 꺼서 전체 토큰을 답변 텍스트에만 쓰게 함.
      providerOptions: {
        google: {
          thinkingConfig: { thinkingBudget: 0 },
        },
      },
      maxOutputTokens: 20,
      maxRetries: 1,
    });
    const normalized = text.trim().toUpperCase();
    // 혹시 모델이 지시를 완전히 안 지키고 앞에 군더더기를 붙이더라도
    // ("답변: YES" 같은 식) 최대한 관대하게 인식하되, NO가 명시돼 있으면
    // 우선함(불확실할 때는 차단 쪽으로 기우는 게 안전).
    if (normalized.includes("NO")) return false;
    if (normalized.includes("YES")) return true;
    console.warn("[scope] 경계선 질문 판단 응답이 비어있거나 애매함 → 안전하게 차단. 원본 응답:", JSON.stringify(text));
    return false;
  } catch (error) {
    console.error("[scope] 경계선 질문 판단 실패 → 안전하게 차단:", error);
    return false;
  }
}